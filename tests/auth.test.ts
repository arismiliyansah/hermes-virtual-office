import { applyD1Migrations, env, SELF } from "cloudflare:test";
import { beforeAll, describe, expect, it } from "vitest";
// @ts-expect-error Vite inlines ?raw imports; this project has no ambient declaration for them.
import initSql from "../migrations/0001_init.sql?raw";
import {
  SESSION_COOKIE,
  createSession,
  hashPassword,
  readSession,
  verifyPassword,
} from "../src/auth";
import { insertUser } from "../src/db";

const db = (env as unknown as { DB: D1Database }).DB;
const SECRET = "dev-secret";
const OWNER_ID = "owner-1";
const OWNER_EMAIL = "owner@example.com";
const OWNER_PASSWORD = "hunter2-correct";

function splitSql(sql: string): string[] {
  return sql
    .split("\n")
    .filter((line) => !line.trimStart().startsWith("--"))
    .join("\n")
    .split(";")
    .map((query) => query.trim())
    .filter(Boolean);
}

function b64url(bytes: Uint8Array): string {
  return btoa(String.fromCharCode(...bytes))
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/, "");
}

function decodeB64url(value: string): string {
  const padded = value.replace(/-/g, "+").replace(/_/g, "/");
  return atob(padded + "===".slice((padded.length + 3) % 4));
}

function cookieToken(res: Response): string {
  const setCookie = res.headers.get("set-cookie");
  expect(setCookie).toBeTruthy();
  const match = /^__Host-session=([^;]*)/.exec(setCookie ?? "");
  expect(match).toBeTruthy();
  return match?.[1] ?? "";
}

function login(password: string = OWNER_PASSWORD): Promise<Response> {
  return SELF.fetch("http://localhost/api/auth/login", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ email: OWNER_EMAIL, password }),
  });
}

function withSession(token: string): Record<string, string> {
  return { cookie: `${SESSION_COOKIE}=${token}` };
}

beforeAll(async () => {
  await applyD1Migrations(db, [
    { name: "0001_init.sql", queries: splitSql(initSql) },
  ]);
  await insertUser(db, {
    id: OWNER_ID,
    email: OWNER_EMAIL,
    passwordHash: await hashPassword(OWNER_PASSWORD),
  });
});

describe("password hashing", () => {
  it("emits the pbkdf2 format used by scripts/hash-password.mjs", async () => {
    const stored = await hashPassword("correct horse");

    expect(stored).toMatch(/^pbkdf2\$100000\$[A-Za-z0-9_-]{22}\$[A-Za-z0-9_-]{43}$/);
    expect(await verifyPassword("correct horse", stored)).toBe(true);
    expect(await verifyPassword("wrong horse", stored)).toBe(false);
  });

  it("accepts a hash generated by scripts/hash-password.mjs for 'password'", async () => {
    const stored =
      "pbkdf2$100000$Hna2Q0Xs4LjxPwOAcRbzIw$qp2O1yVvsh-APvJ_BbvpF_paVYyXm-NPeYs_TCIZdeE";

    expect(await verifyPassword("password", stored)).toBe(true);
    expect(await verifyPassword("Password", stored)).toBe(false);
  });

  it("rejects malformed stored hashes instead of throwing", async () => {
    for (const stored of ["", "plain", "pbkdf2$100000$only-three", "bcrypt$100000$aa$bb"]) {
      expect(await verifyPassword("password", stored)).toBe(false);
    }
  });
});

describe("sessions", () => {
  it("round-trips the uid and csrf claims with a 7-day exp", () => {
    const now = new Date();
    const token = createSession(OWNER_ID, SECRET, now);

    const session = readSession(token, SECRET, now);
    expect(session?.userId).toBe(OWNER_ID);
    expect(session?.csrf).toMatch(/^[A-Za-z0-9_-]+$/);

    const payload = JSON.parse(decodeB64url(token.split(".")[0])) as {
      uid: string;
      csrf: string;
      exp: number;
    };
    expect(Object.keys(payload).sort()).toEqual(["csrf", "exp", "uid"]);
    expect(payload.uid).toBe(OWNER_ID);
    expect(payload.csrf).toBe(session?.csrf);
    expect(payload.exp).toBe(Math.floor(now.getTime() / 1000) + 7 * 24 * 60 * 60);
  });

  it("signs the payload with HMAC-SHA256", async () => {
    const token = createSession(OWNER_ID, SECRET);
    const [payload, signature] = token.split(".");

    const key = await crypto.subtle.importKey(
      "raw",
      new TextEncoder().encode(SECRET),
      { name: "HMAC", hash: "SHA-256" },
      false,
      ["sign"],
    );
    const expected = b64url(
      new Uint8Array(
        await crypto.subtle.sign("HMAC", key, new TextEncoder().encode(payload)),
      ),
    );

    expect(signature).toBe(expected);
  });

  it("rejects tampered, foreign and expired sessions", () => {
    const token = createSession(OWNER_ID, SECRET);
    const [payload, signature] = token.split(".");
    const forgedPayload = b64url(
      new TextEncoder().encode(
        JSON.stringify({ uid: "intruder", csrf: "x", exp: 9999999999 }),
      ),
    );

    expect(readSession(`${forgedPayload}.${signature}`, SECRET)).toBeNull();
    expect(readSession(token, "other-secret")).toBeNull();
    expect(readSession("not-a-session", SECRET)).toBeNull();

    const expired = createSession(
      OWNER_ID,
      SECRET,
      new Date(Date.now() - 8 * 24 * 60 * 60 * 1000),
    );
    expect(readSession(expired, SECRET)).toBeNull();
    expect(JSON.parse(decodeB64url(payload)).uid).toBe(OWNER_ID);
  });
});

describe("POST /api/auth/login", () => {
  it("sets a __Host- session cookie without Domain", async () => {
    const res = await login();

    expect(res.status).toBe(200);
    const body = (await res.json()) as { csrf: string };
    expect(body.csrf).toMatch(/^[A-Za-z0-9_-]+$/);

    const setCookie = res.headers.get("set-cookie") ?? "";
    expect(setCookie).toContain("__Host-session=");
    expect(setCookie).toContain("Secure");
    expect(setCookie).toContain("Path=/");
    expect(setCookie).toContain("HttpOnly");
    expect(setCookie).toContain("SameSite=Lax");
    expect(setCookie).toContain("Max-Age=604800");
    expect(setCookie).not.toContain("Domain=");

    const session = readSession(cookieToken(res), SECRET);
    expect(session?.userId).toBe(OWNER_ID);
    expect(body.csrf).toBe(session?.csrf);
  });

  it("rejects a wrong password with 401", async () => {
    const res = await login("definitely-not-it");

    expect(res.status).toBe(401);
    expect(res.headers.get("set-cookie")).toBeNull();
  });

  it("rejects an unknown email with 401", async () => {
    const res = await SELF.fetch("http://localhost/api/auth/login", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ email: "nobody@example.com", password: OWNER_PASSWORD }),
    });

    expect(res.status).toBe(401);
  });
});

describe("GET /api/auth/me", () => {
  it("returns the user id for a valid session", async () => {
    const loginRes = await login();
    const token = cookieToken(loginRes);

    const res = await SELF.fetch("http://localhost/api/auth/me", {
      headers: withSession(token),
    });

    expect(res.status).toBe(200);
    expect(await res.json()).toEqual({ userId: OWNER_ID });
  });

  it("rejects an expired session with 401", async () => {
    const expired = createSession(
      OWNER_ID,
      SECRET,
      new Date(Date.now() - 8 * 24 * 60 * 60 * 1000),
    );

    const res = await SELF.fetch("http://localhost/api/auth/me", {
      headers: withSession(expired),
    });

    expect(res.status).toBe(401);
  });

  it("rejects a tampered session cookie with 401", async () => {
    const loginRes = await login();
    const [payload, signature] = cookieToken(loginRes).split(".");
    const forgedPayload = b64url(
      new TextEncoder().encode(
        JSON.stringify({ uid: "intruder", csrf: "x", exp: 9999999999 }),
      ),
    );

    const res = await SELF.fetch("http://localhost/api/auth/me", {
      headers: withSession(`${forgedPayload}.${signature}`),
    });

    expect(res.status).toBe(401);
  });

  it("rejects a request without a session with 401", async () => {
    const res = await SELF.fetch("http://localhost/api/auth/me");

    expect(res.status).toBe(401);
  });
});

describe("CSRF on mutations", () => {
  it("rejects a mutation without x-csrf-token with 403", async () => {
    const loginRes = await login();
    const token = cookieToken(loginRes);

    const res = await SELF.fetch("http://localhost/api/auth/logout", {
      method: "POST",
      headers: withSession(token),
    });

    expect(res.status).toBe(403);
    expect(await res.json()).toEqual({ error: "csrf" });
  });

  it("rejects a mutation with the wrong x-csrf-token with 403", async () => {
    const loginRes = await login();
    const token = cookieToken(loginRes);

    const res = await SELF.fetch("http://localhost/api/auth/logout", {
      method: "POST",
      headers: { ...withSession(token), "x-csrf-token": "not-the-token" },
    });

    expect(res.status).toBe(403);
  });

  it("rejects a mutation without a session with 403", async () => {
    const res = await SELF.fetch("http://localhost/api/auth/logout", {
      method: "POST",
      headers: { "x-csrf-token": "anything" },
    });

    expect(res.status).toBe(403);
  });

  it("lets a mutation through with the matching token and clears the cookie", async () => {
    const loginRes = await login();
    const { csrf } = (await loginRes.json()) as { csrf: string };
    const token = cookieToken(loginRes);

    const res = await SELF.fetch("http://localhost/api/auth/logout", {
      method: "POST",
      headers: { ...withSession(token), "x-csrf-token": csrf },
    });

    expect(res.status).toBe(204);
    const setCookie = res.headers.get("set-cookie") ?? "";
    expect(setCookie).toContain("__Host-session=;");
    expect(setCookie).toContain("Max-Age=0");
    expect(setCookie).not.toContain("Domain=");
  });

  it("does not require CSRF for login itself", async () => {
    const res = await login();

    expect(res.status).toBe(200);
  });
});
